def wrong_opts(ans, diff):
    try: ans = int(float(ans))
    except: ans = 0
    offs = {-5,-4,-3,-2,-1,1,2,3,4,5} if diff=='easy' else {-15,-12,-10,-8,-5,-4,-3,-2,2,3,4,5,8,10,12,15} if diff=='medium' else {-25,-20,-18,-15,-12,-10,-8,8,10,12,15,18,20,25}
    w = set()
    while len(w) < 3:
        o = random.choice(list(offs))
        v = ans + o
        if v > 0 and str(v) != str(ans): w.add(str(v))
    return list(w)

def make_choices(correct, wrongs):
    opts = list(wrongs) + [str(correct)]
    random.shuffle(opts)
    return opts[:4]

def mkq(tc, skill, qt, ans, ex, ht, ss, model, cwr, qtype, rl, diff, conf, seq):
    ch = make_choices(ans, wrong_opts(ans, diff))
    return {
        'question_id': f'{tc}_q{seq:04d}',
        'grade_level': int(tc[1]),
        'lesson_id': tc,
        'topic_code': tc,
        'skill_code': skill,
        'question_type': qtype,
        'routine_level': rl,
        'difficulty': diff,
        'confidence_role': conf,
        'question_text_th': qt,
        'choices': ch,
        'correct_answer': str(ans),
        'explanation_th': ex,
        'hint_th': ht,
        'solution_strategy_th': ss,
        'singapore_math_model': model,
        'common_wrong_reason_th': cwr,
    }

def save_jsonl(tc, qs):
    g = int(tc[1])
    d = BASE / f'grade_{g}'
    d.mkdir(parents=True, exist_ok=True)
    p = d / f'{tc}.jsonl'
    with open(p, 'w', encoding='utf-8') as f:
        for q in qs:
            f.write(json.dumps(q, ensure_ascii=False) + '\n')
    print(f'  Wrote {len(qs)} -> {p.name}')

