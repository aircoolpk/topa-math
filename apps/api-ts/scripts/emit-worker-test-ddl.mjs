/**
 * Writes the DDL of the tables the Worker reaches with raw SQL.
 *
 * The Drizzle migration creates every table the ORM knows, but the billing
 * and the MPP integration use raw SQL, so their tables never made it into
 * the schema file. The integration tests build their database from the
 * Drizzle migration, which means those tables are missing.
 *
 * The DDL is read from the live test branch, whose schema is the same shape
 * as the production schema, so the test database matches production.
 *
 *   node scripts/emit-worker-test-ddl.mjs
 */
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const { Client } = require('pg')

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = join(HERE, 'billing-ddl.sql')

/** The tables the Worker reads and writes with raw SQL. */
const TABLES = [
  'billing_checkout_reservations',
  'mpp_package_prices',
  'mpp_purchase_orders',
  'mpp_purchase_events',
  'mpp_test_transactions',
  'mpp_test_webhook_events',
  'site_announcements',
]

/**
 * The Neon URL asks for `sslmode=require`, which the `pg` driver treats as
 * an alias for `verify-full` today but will read with the weaker libpq
 * meaning in `pg` v9. The strict mode is spelled out so the certificate
 * keeps being verified. A URL without an SSL mode is left alone: it may
 * point at a server that does not speak SSL at all.
 */
function withVerifiedSsl(connectionString) {
  if (!connectionString) return connectionString
  if (!connectionString.includes('sslmode=')) return connectionString
  if (connectionString.includes('sslmode=verify-full')) return connectionString
  return connectionString.replace(/sslmode=[^&]+/, 'sslmode=verify-full')
}

/** Reads the test branch URL from apps/api-ts/.env.test. */
function testUrl() {
  const env = readFileSync(join(HERE, '..', '.env.test'), 'utf-8')
  const match = env.match(/^TEST_DATABASE_URL=["']?([^"'\r\n]+)/m)
  if (!match) throw new Error('TEST_DATABASE_URL is missing from apps/api-ts/.env.test')
  return withVerifiedSsl(match[1])
}

function quoteIdent(name) {
  return `"${name.replace(/"/g, '""')}"`
}

function quoteLiteral(value) {
  return `'${value.replace(/'/g, "''")}'`
}

/** The SQL type of a column, without the default. */
function columnType(info) {
  const type = info.data_type
  if (type === 'ARRAY') return info.udt_name.replace(/^_/, '')
  if (type === 'character varying') return `varchar(${info.character_maximum_length ?? 255})`
  if (type === 'numeric') return `numeric(${info.numeric_precision ?? 18}, ${info.numeric_scale ?? 0})`
  if (type === 'timestamp with time zone') return 'timestamptz'
  if (type === 'time without time zone') return 'time'
  if (type === 'USER-DEFINED' || type === 'jsonb') return info.udt_name
  return type
}

async function main() {
  const client = new Client({ connectionString: testUrl() })
  await client.connect()

  const indexStatements = []
  const chunks = [
    '-- Generated by apps/api-ts/scripts/emit-worker-test-ddl.mjs',
    '-- The tables the Worker reaches with raw SQL. Do not edit by hand.',
    '',
  ]

  for (const table of TABLES) {
    const columns = await client.query(
      `SELECT column_name, data_type, udt_name, is_nullable, column_default,
              character_maximum_length, numeric_precision, numeric_scale
         FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = $1
        ORDER BY ordinal_position`,
      [table],
    )
    if (!columns.rows.length) throw new Error(`table ${table} does not exist on the test branch`)

    const primary = await client.query(
      `SELECT a.attname AS column_name
         FROM pg_index i
         JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
        WHERE i.indrelid = $1::regclass AND i.indisprimary`,
      [table],
    )
    const unique = await client.query(
      `SELECT a.attname AS column_name, i.indisunique
         FROM pg_index i
         JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
        WHERE i.indrelid = $1::regclass AND i.indisunique AND NOT i.indisprimary
        GROUP BY a.attname, i.indisunique`,
      [table],
    )
    const foreign = await client.query(
      `SELECT tc.constraint_name, kcu.column_name,
              ccu.table_name AS foreign_table, ccu.column_name AS foreign_column
         FROM information_schema.table_constraints tc
         JOIN information_schema.key_column_usage kcu
           ON tc.constraint_name = kcu.constraint_name
         JOIN information_schema.constraint_column_usage ccu
           ON tc.constraint_name = ccu.constraint_name
        WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_name = $1`,
      [table],
    )
    const indexes = await client.query(
      `SELECT indexname, indexdef FROM pg_indexes
        WHERE schemaname = 'public' AND tablename = $1 AND indexname NOT LIKE '%_pkey'`,
      [table],
    )

    const parts = columns.rows.map((column) => {
      const type = columnType(column)
      const nullable = column.is_nullable === 'YES' ? '' : ' NOT NULL'
      let def = ''
      const raw = column.column_default
      if (raw && !raw.startsWith('nextval')) {
        def = ` DEFAULT ${raw}`
      } else if (raw && raw.startsWith('nextval')) {
        const sequence = raw.match(/nextval\('([^']+)'::regclass\)/)
        if (sequence) {
          chunks.push(`DROP SEQUENCE IF EXISTS ${quoteIdent(sequence[1])} CASCADE;`)
          def = ` DEFAULT nextval('${sequence[1]}'::regclass)`
        }
      }
      return `  ${quoteIdent(column.column_name)} ${type}${nullable}${def}`
    })

    if (primary.rows.length) {
      parts.push(
        `  PRIMARY KEY (${primary.rows.map((row) => quoteIdent(row.column_name)).join(', ')})`,
      )
    }
    for (const constraint of unique.rows) {
      parts.push(`  UNIQUE (${quoteIdent(constraint.column_name)})`)
    }
    for (const constraint of foreign.rows) {
      parts.push(
        `  FOREIGN KEY (${quoteIdent(constraint.column_name)}) ` +
          `REFERENCES ${quoteIdent(constraint.foreign_table)} (${quoteIdent(constraint.foreign_column)})`,
      )
    }

    chunks.push(`DROP TABLE IF EXISTS ${quoteIdent(table)} CASCADE;`)
    chunks.push(`CREATE TABLE ${quoteIdent(table)} (`)
    chunks.push(parts.join(',\n'))
    chunks.push(');')
    chunks.push('')
    indexStatements.push(
      ...indexes.rows.map((index) =>
        `${index.indexdef.replace(/CREATE (UNIQUE )?INDEX/, 'CREATE $1INDEX IF NOT EXISTS')};`,
      ),
    )
  }

  // Every index comes after every table: an index can point at a table that
  // a later foreign key depends on.
  chunks.push(...indexStatements)
  chunks.push('')

  await client.end()
  writeFileSync(OUT, chunks.join('\n'), 'utf-8')
  console.log(`wrote ${OUT} (${TABLES.length} tables)`)
}

main().catch((error) => {
  console.error(error.message)
  process.exit(1)
})
